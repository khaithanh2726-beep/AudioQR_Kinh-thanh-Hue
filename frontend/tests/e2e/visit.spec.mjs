import { test, expect } from '@playwright/test'
import { readFile, copyFile, writeFile } from 'node:fs/promises'
import { join, resolve } from 'node:path'
import { randomUUID, createHash } from 'node:crypto'
import { execFileSync } from 'node:child_process'

const runtimeRoot = process.env.HUEQR_E2E_RUNTIME
const baseURL = process.env.HUEQR_E2E_URL || 'http://localhost:15173'
test.skip(!runtimeRoot, 'Cần cấu hình runtime MySQL và audio thử riêng.')
test.describe.configure({ mode: 'serial' })

test('Admin applies a real Vietnamese audio pair and a guest reads and plays it', async ({ page, browser }) => {
  const runtime = JSON.parse((await readFile(join(runtimeRoot, 'runtime.json'), 'utf8')).replace(/^\uFEFF/, ''))
  expect(runtime.container).toMatch(/^hueqr-e2e-/)
  const source = await readFile(resolve('../docs/05-noi-dung/thuyet-minh-vi-v01.md'), 'utf8')
  const text = source.split('## 1. Cổng Ngọ Môn')[1].split('<a id="thai-hoa">')[0].trim()
  const problems = []
  const visitorName = 'Khách kiểm thử ' + randomUUID().slice(0, 8)
  page.on('pageerror', error => problems.push(error.message))
  await page.goto('/admin.html')
  await page.locator('#login-name').fill('smoke-admin')
  await page.locator('#login-password').fill(runtime.adminPassword)
  await page.getByRole('button', { name: 'Đăng nhập', exact: true }).click()
  await expect(page.getByRole('button', { name: 'Thêm địa điểm', exact: true })).toBeVisible()

  await page.getByRole('button', { name: 'Thêm địa điểm', exact: true }).click()
  const placeName = 'Ngọ Môn · kiểm thử ' + randomUUID().slice(0, 8)
  await page.locator('#place-name').fill(placeName)
  const created = page.waitForResponse(response => response.url().endsWith('/api/v1/admin/places') && response.request().method() === 'POST')
  await page.getByRole('button', { name: 'Lưu địa điểm', exact: true }).click()
  const placeId = (await (await created).json()).result.placeId
  await expect(page.getByText('Không có thay đổi chưa lưu', { exact: true })).toBeVisible()
  await page.getByRole('button', { name: 'Về danh sách', exact: true }).click()
  const card = () => page.locator('.admin-place').filter({ hasText: placeId })
  await card().getByRole('button', { name: 'Vùng tương tác' }).click()
  const vertices = [[107.5775, 16.468], [107.5785, 16.468], [107.578, 16.469]]
  for (let i = 0; i < vertices.length; i++) {
    await page.getByRole('button', { name: 'Thêm đỉnh để nhập tọa độ' }).click()
    await page.locator('#lng-' + i).fill(String(vertices[i][0]))
    await page.locator('#lat-' + i).fill(String(vertices[i][1]))
    await page.locator('#lat-' + i).press('Tab')
  }
  await page.getByRole('button', { name: 'Khép vùng' }).click()
  await page.getByRole('button', { name: 'Xem trước đúng hình hiện tại' }).click()
  await page.getByRole('button', { name: 'Lưu bản sửa', exact: true }).click()
  const appliedRegion = page.waitForResponse(response => response.url().endsWith('/active-region') && response.request().method() === 'PUT')
  await page.getByRole('button', { name: 'Áp dụng đúng bản đã xem và lưu' }).click()
  expect((await appliedRegion).status()).toBe(200)
  await page.getByRole('button', { name: 'Về danh sách', exact: true }).click()
  await card().getByRole('button', { name: 'Nội dung và cặp' }).click()
  await page.locator('#text-body').fill(text)
  const saved = page.waitForResponse(response => response.url().endsWith('/text-revisions') && response.request().method() === 'POST')
  await page.getByRole('button', { name: 'Lưu nháp văn bản', exact: true }).click()
  const textId = (await (await saved).json()).result.textRevisionId
  await expect(page.getByText('Không có phần chưa lưu', { exact: true })).toBeVisible()

  await page.getByRole('button', { name: 'Về danh sách', exact: true }).click()
  await card().getByRole('button', { name: 'Sửa thông tin' }).click()
  const blocked = page.waitForResponse(response => response.url().endsWith('/visibility') && response.request().method() === 'PUT')
  await page.getByRole('button', { name: 'Bật hiển thị', exact: true }).click()
  expect((await blocked).status()).toBe(409)

  const wav = await readFile(process.env.HUEQR_E2E_WAV)
  let dataSize = 0
  for (let offset = 12; offset + 8 <= wav.length;) {
    const size = wav.readUInt32LE(offset + 4)
    if (wav.toString('ascii', offset, offset + 4) === 'data') dataSize = size
    offset += 8 + size + (size % 2)
  }
  expect(dataSize).toBeGreaterThan(0)
  const wavId = randomUUID()
  await copyFile(process.env.HUEQR_E2E_WAV, join(runtime.audioRoot, wavId + '.wav'))
  const sql = await readFile(resolve('../backend/src/test/fixtures/smoke/stage-smoke-wav.sql'), 'utf8')
  const variables = `SET @smoke_text_id='${textId}', @smoke_wav_id='${wavId}', @smoke_wav_hash='${createHash('sha256').update(wav).digest('hex')}', @smoke_wav_size=${wav.length}, @smoke_wav_duration=${(dataSize / 48000).toFixed(9)};\n`
  const output = execFileSync('docker', ['exec', '-i', '-e', 'MYSQL_PWD', runtime.container, 'mysql', '-u', 'hueqr_smoke', '-N', 'hueqr_smoke'], {
    env: { ...process.env, MYSQL_PWD: runtime.dbPassword }, input: variables + sql, encoding: 'utf8',
  })
  const jobId = output.trim()
  expect(jobId).toMatch(/^[0-9a-f-]{36}$/)
  const read = path => page.evaluate(async path => {
    const response = await fetch('/api/v1' + path, { credentials: 'same-origin', cache: 'no-store' })
    if (!response.ok) throw new Error('API status ' + response.status)
    return response.json()
  }, path)
  await expect.poll(async () => (await read('/admin/tts-jobs/' + jobId)).phase, { timeout: 45000 }).toBe('SUCCEEDED')
  const job = await read('/admin/tts-jobs/' + jobId)
  await page.getByRole('button', { name: 'Về danh sách', exact: true }).click()
  await card().getByRole('button', { name: 'Nội dung và cặp' }).click()
  await page.locator('#audio-id').selectOption(job.result.audioRevisionId)
  await page.getByRole('button', { name: 'Đọc và đối chiếu audio' }).click()
  await page.getByRole('button', { name: 'Tải để nghe thử' }).click()
  const preview = page.locator('audio')
  await expect(preview).toHaveAttribute('src', /^blob:/)
  await preview.evaluate(audio => audio.play())
  await expect.poll(() => preview.evaluate(audio => !audio.paused && audio.duration > 0)).toBe(true)
  await preview.evaluate(audio => audio.pause())
  await page.locator('#text-locator').fill('smoke-review:text:' + textId)
  await page.getByRole('button', { name: 'Ghi tham chiếu cho văn bản đã lưu' }).click()
  await expect(page.getByText('Không có phần chưa lưu', { exact: true })).toBeVisible()
  await page.locator('#audio-locator').fill('smoke-review:audio:' + job.result.audioRevisionId)
  await page.getByRole('button', { name: 'Ghi tham chiếu cho audio đã lưu' }).click()
  await page.getByRole('button', { name: 'Áp dụng văn bản và audio', exact: true }).click()
  await page.getByRole('button', { name: 'Về danh sách', exact: true }).click()
  await card().getByRole('button', { name: 'Sửa thông tin' }).click()
  const visible = page.waitForResponse(response => response.url().endsWith('/visibility') && response.request().method() === 'PUT')
  await page.getByRole('button', { name: 'Bật hiển thị', exact: true }).click()
  expect((await visible).status()).toBe(200)

  const guestContext = await browser.newContext()
  const guest = await guestContext.newPage()
  guest.on('pageerror', error => problems.push(error.message))
  await guest.goto(baseURL)
  await guest.locator('input[name="displayName"]').fill(visitorName)
  await guest.getByRole('button', { name: 'Bắt đầu tham quan' }).click()
  await expect(guest.locator('.map-canvas')).toBeVisible()
  await guest.locator('.map-canvas').click()
  const overlapping = guest.getByRole('button', { name: placeName, exact: true })
  if (await overlapping.isVisible()) await overlapping.click()
  await expect(guest.locator('.text-body')).toHaveText(text)
  await expect(guest.locator('audio')).toHaveAttribute('src', /^blob:/)
  await expect.poll(() => guest.locator('audio').evaluate(audio => !audio.paused && audio.currentTime > 0), { timeout: 15000 }).toBe(true)
  await guest.screenshot({ path: join(runtimeRoot, 'guest-visit.png'), fullPage: true })
  await page.bringToFront()
  await page.getByRole('button', { name: 'Phiên và thống kê', exact: true }).click()
  await page.getByRole('textbox', { name: 'Tên hoặc mã phiên' }).fill(visitorName)
  await page.getByRole('button', { name: 'Xem dữ liệu' }).click()
  await expect(page.getByRole('cell', { name: visitorName, exact: true })).toBeVisible()
  await page.getByRole('row').filter({ has: page.getByRole('cell', { name: visitorName, exact: true }) }).getByRole('button', { name: 'Xem', exact: true }).click()
  const sessionDialog = page.getByRole('dialog', { name: /Chi tiết phiên/ })
  await expect(sessionDialog).toBeVisible()
  expect(await sessionDialog.evaluate(element => element.matches(':modal'))).toBe(true)
  await expect(sessionDialog.getByText(visitorName, { exact: false })).toBeVisible()
  await sessionDialog.getByRole('button', { name: 'Đóng', exact: true }).click()
  await expect(sessionDialog).not.toBeVisible()
  await page.getByRole('button', { name: 'Thống kê', exact: true }).click()
  await page.getByRole('button', { name: 'Xem dữ liệu' }).click()
  await expect(page.getByRole('heading', { name: /Lượt xem trong khoảng — tổng [1-9]/ })).toBeVisible()
  await page.screenshot({ path: join(runtimeRoot, 'admin-statistics.png'), fullPage: true })
  await page.getByRole('button', { name: 'QR chung', exact: true }).click()
  await expect(page.getByText('Chưa có URL triển khai.', { exact: false })).toBeVisible()
  await page.getByRole('button', { name: 'Địa điểm', exact: true }).click()
  await card().getByRole('button', { name: 'Nội dung và cặp' }).click()
  await page.locator('#text-body').fill(text + '\nBản nháp thay đổi trong kiểm thử, chưa áp dụng.')
  await page.getByRole('button', { name: 'Lưu nháp văn bản', exact: true }).click()
  await expect(page.getByText('Không có phần chưa lưu', { exact: true })).toBeVisible()
  await expect(page.getByText('Chưa có tác vụ cho bản nháp này.', { exact: true })).toBeVisible()
  await expect(page.locator('#audio-id option')).toHaveCount(1)
  await expect(page.getByRole('button', { name: 'Đọc và đối chiếu audio', exact: true })).toBeDisabled()
  await expect(page.getByRole('button', { name: 'Tải để nghe thử', exact: true })).not.toBeVisible()
  await guest.reload()
  await expect(guest.locator('.text-body')).toHaveText(text)
  expect(problems).toEqual([])
  await writeFile(join(runtimeRoot, 'e2e-result.json'), JSON.stringify({
    placeId, placeName, visitorName, textId, jobId, audioId: job.result.audioRevisionId, realWavBytes: wav.length,
    assertions: ['hidden place gate', 'WAV to MP3', 'Admin preview decode', 'pair apply', 'guest playback', 'view statistics', 'native session modal', 'QR pending URL', 'new draft clears old audio and job; applied guest content preserved'],
    completedAt: new Date().toISOString(),
  }, null, 2))
  await guestContext.close()
})

test('mobile guest can read through an audio network error, retry and reload the same visit', async ({ page }) => {
  const prior = JSON.parse(await readFile(join(runtimeRoot, 'e2e-result.json'), 'utf8'))
  expect(typeof prior.placeName).toBe('string')
  await page.setViewportSize({ width: 390, height: 844 })
  await page.route('**/content-grants/*/audio', route => route.abort())
  await page.goto('/')
  await page.locator('input[name="displayName"]').fill('Khách mạng lỗi')
  await page.getByRole('button', { name: 'Bắt đầu tham quan' }).click()
  await page.locator('.map-canvas').click()
  const overlapping = page.getByRole('button', { name: prior.placeName, exact: true })
  if (await overlapping.isVisible()) await overlapping.click()
  await expect(page.locator('.text-body')).toBeVisible()
  await expect(page.getByText('Chưa phát được audio.', { exact: false })).toBeVisible()
  await page.unroute('**/content-grants/*/audio')
  await page.getByRole('button', { name: 'Thử lại', exact: true }).click()
  await expect(page.locator('audio')).toHaveAttribute('src', /^blob:/)
  expect(await page.locator('audio').evaluate(audio => audio.paused)).toBe(true)
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
  await page.reload()
  await expect(page.locator('.text-body')).toBeVisible()
  await expect(page.locator('audio')).toHaveAttribute('src', /^blob:/)
  expect(await page.locator('audio').evaluate(audio => audio.paused)).toBe(true)
  await page.screenshot({ path: join(runtimeRoot, 'mobile-visit.png'), fullPage: true })
  await page.getByRole('button', { name: 'Kết thúc tham quan', exact: true }).click()
  await expect(page.getByRole('heading', { name: 'Đã kết thúc tham quan', exact: true })).toBeVisible()
})
